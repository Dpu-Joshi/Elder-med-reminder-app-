package com.medreminder.data.remote

import android.app.Activity
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.firestore.FieldValue
import com.google.firebase.firestore.SetOptions
import com.google.firebase.firestore.snapshots
import com.google.firebase.storage.StorageMetadata
import com.medreminder.R
import com.medreminder.data.Dose
import com.medreminder.data.Elder
import com.medreminder.data.Language
import com.medreminder.data.Medicine
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.map
import kotlinx.coroutines.tasks.await

/** Family mode: Google sign-in, the family's elders, their medicines, and answering alerts. */
class FamilyRepository {

    val user: FirebaseUser? get() = Fb.auth.currentUser?.takeUnless { it.isAnonymous }

    private fun uid(): String = user?.uid ?: error("Not signed in")

    /** Google sign-in through Credential Manager; [activity] hosts the account picker. */
    suspend fun signInWithGoogle(activity: Activity) {
        val option = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(false)
            // Generated by the google-services plugin once Google sign-in is enabled in Firebase.
            .setServerClientId(activity.getString(R.string.default_web_client_id))
            .build()
        val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
        val credential = CredentialManager.create(activity).getCredential(activity, request).credential
        require(credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
            "Unexpected credential type"
        }
        val idToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
        Fb.auth.signInWithCredential(GoogleAuthProvider.getCredential(idToken, null)).await()
        onSignedIn()
    }

    suspend fun onSignedIn() {
        val u = user ?: return
        Fb.db.document(Paths.user(u.uid))
            .set(mapOf("displayName" to (u.displayName ?: u.email.orEmpty())), SetOptions.merge())
            .await()
        runCatching { registerToken() }
    }

    suspend fun registerToken(token: String? = null) {
        val u = user ?: return
        val value = token ?: Fb.messaging.token.await()
        Fb.db.document(Paths.user(u.uid))
            .set(mapOf("fcmTokens" to FieldValue.arrayUnion(value)), SetOptions.merge())
            .await()
    }

    fun signOut() = Fb.auth.signOut()

    // ---- Reading ----

    /** Set by the server when this person first pairs an elder or joins a family. */
    fun observeFamilyId(): Flow<String?> =
        Fb.db.document(Paths.user(uid())).snapshots().map { it.getString("familyId") }

    fun observeFamily(familyId: String): Flow<FamilyInfo?> =
        Fb.db.document(Paths.family(familyId)).snapshots().map { if (it.exists()) it.toFamily() else null }

    fun observeElders(familyId: String): Flow<List<Elder>> =
        Fb.db.collection(Paths.elders(familyId)).snapshots().map { q -> q.documents.map { it.toElder() }.sortedBy { it.name } }

    fun observeElder(familyId: String, elderId: String): Flow<Elder?> =
        Fb.db.document(Paths.elder(familyId, elderId)).snapshots().map { if (it.exists()) it.toElder() else null }

    fun observeMedicines(familyId: String, elderId: String): Flow<List<Medicine>> =
        Fb.db.collection(Paths.medicines(familyId, elderId)).snapshots()
            .map { q -> q.documents.map { it.toMedicine() }.sortedWith(compareBy({ !it.active }, { it.times.minOrNull() })) }

    fun observeDoses(familyId: String, elderId: String, localDate: String): Flow<List<Dose>> =
        Fb.db.collection(Paths.doses(familyId, elderId)).whereEqualTo("localDate", localDate).snapshots()
            .map { q -> q.documents.map { it.toDose() }.sortedBy { it.scheduledAt } }

    fun observeDose(familyId: String, elderId: String, doseId: String): Flow<Dose?> =
        Fb.db.document("${Paths.doses(familyId, elderId)}/$doseId").snapshots().map { if (it.exists()) it.toDose() else null }

    fun observeMedicine(familyId: String, elderId: String, medicineId: String): Flow<Medicine?> =
        Fb.db.document("${Paths.medicines(familyId, elderId)}/$medicineId").snapshots()
            .map { if (it.exists()) it.toMedicine() else null }

    suspend fun photoUrl(path: String): String? =
        runCatching { Fb.storage.reference.child(path).downloadUrl.await().toString() }.getOrNull()

    // ---- Pairing and family ----

    suspend fun claimPairingCode(
        code: String,
        elderName: String,
        nickname: String,
        language: Language,
        phoneNumber: String,
    ): Pair<String, String> {
        val result = Fb.functions.getHttpsCallable("claimPairingCode").call(
            mapOf(
                "code" to code,
                "elderName" to elderName,
                "nickname" to nickname,
                "language" to language.wire,
                "phoneNumber" to phoneNumber,
            ),
        ).await()
        val data = result.getData() as Map<*, *>
        return data["familyId"] as String to data["elderId"] as String
    }

    suspend fun createInvite(): String {
        val result = Fb.functions.getHttpsCallable("createFamilyInvite").call().await()
        return (result.getData() as Map<*, *>)["code"] as String
    }

    suspend fun joinFamily(code: String) {
        Fb.functions.getHttpsCallable("joinFamily").call(mapOf("code" to code)).await()
    }

    suspend fun updateElder(familyId: String, elderId: String, fields: Map<String, Any?>) {
        Fb.db.document(Paths.elder(familyId, elderId)).update(fields).await()
    }

    suspend fun setAlertOrder(familyId: String, order: List<String>) {
        Fb.db.document(Paths.family(familyId)).update("alertOrder", order).await()
    }

    // ---- Medicines ----

    /** Saves a medicine, uploading a new photo first when one was taken. Returns its id. */
    suspend fun saveMedicine(familyId: String, elderId: String, medicine: Medicine, newPhotoJpeg: ByteArray?): String {
        val collection = Fb.db.collection(Paths.medicines(familyId, elderId))
        val isNew = medicine.id.isEmpty()
        val ref = if (isNew) collection.document() else collection.document(medicine.id)

        var photoPath = medicine.photoPath
        if (newPhotoJpeg != null) {
            val path = Paths.photo(familyId, elderId, ref.id, System.currentTimeMillis())
            val metadata = StorageMetadata.Builder().setContentType("image/jpeg").build()
            Fb.storage.reference.child(path).putBytes(newPhotoJpeg, metadata).await()
            medicine.photoPath?.let { old -> runCatching { Fb.storage.reference.child(old).delete().await() } }
            photoPath = path
        }

        val me = uid()
        val data = medicine.copy(photoPath = photoPath).toFirestore().toMutableMap()
        data["updatedBy"] = me
        data["updatedAt"] = FieldValue.serverTimestamp()
        if (isNew) {
            data["addedBy"] = me
            data["addedAt"] = FieldValue.serverTimestamp()
            ref.set(data).await()
        } else {
            ref.set(data, SetOptions.merge()).await()
        }
        return ref.id
    }

    /** Stopping keeps the history; the server removes its future doses. */
    suspend fun stopMedicine(familyId: String, elderId: String, medicineId: String) {
        Fb.db.document("${Paths.medicines(familyId, elderId)}/$medicineId")
            .update(mapOf("active" to false, "updatedBy" to uid(), "updatedAt" to FieldValue.serverTimestamp()))
            .await()
    }

    // ---- Answering alerts ----

    /** "She took it, I checked." */
    suspend fun markChecked(familyId: String, elderId: String, doseId: String) {
        Fb.db.document("${Paths.doses(familyId, elderId)}/$doseId").update(
            mapOf(
                "status" to "confirmed_by_family",
                "confirmedBy" to uid(),
                "confirmedAt" to System.currentTimeMillis().toTimestamp(),
                "alertAt" to null,
            ),
        ).await()
    }

    /** Tapped Call: this person is on it, so the next contact is not alerted. */
    suspend fun acknowledge(familyId: String, elderId: String, doseId: String) {
        Fb.db.document("${Paths.doses(familyId, elderId)}/$doseId").update(
            mapOf(
                "acknowledgedBy" to uid(),
                "acknowledgedAt" to System.currentTimeMillis().toTimestamp(),
                "alertAt" to null,
            ),
        ).await()
    }
}
